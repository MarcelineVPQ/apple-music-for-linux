#!/usr/bin/env node
// Builds licenses/hyphenation-NOTICES.txt: the copyright and licence notice of every hyphenation
// pattern file Sonata ships (package.json build.files, about-data.js PATTERNS), taken verbatim from
// the original hyph-utf8 file's header in the upstream tex-hyphen repository at a pinned commit.
// The `hyphen` package's converted pattern files drop those headers; this file carries them.
//
//   node tools/hyph-notices.js            write the file (needs the network: raw.githubusercontent.com)
//   node tools/hyph-notices.js --check    exit 1 when the file lacks a section for a shipped pattern
'use strict'
const fs = require('fs')
const path = require('path')

const COMMIT = '5684c0f51c0b81133db2efbe60a408b4155a3ff5'   // tex-hyphen master, 2026-10-17
const RAW = (code) => `https://raw.githubusercontent.com/hyphenation/tex-hyphen/${COMMIT}/hyph-utf8/tex/generic/hyph-utf8/patterns/tex/hyph-${code}.tex`
const OUT = path.join(__dirname, '..', 'licenses', 'hyphenation-NOTICES.txt')
const { PATTERNS } = require('../about-data')

// the header's comment lines from the top through the end of its "licence:" block (title,
// copyright, notice, language, version, authors, licence), '% ' prefixes removed
function notice(tex) {
  const out = []
  let inLicence = false
  // loop: NOT-WORTH — a header's lines, once per pattern file, tool only
  for (const line of tex.split('\n')) {
    if (!line.startsWith('%')) break
    const body = line.replace(/^% ?/, '')
    const key = /^([a-z_]+):/.exec(body)
    if (key && inLicence) break
    if (key && key[1] === 'licence') inLicence = true
    if (key && ['hyphenmins', 'texlive', 'changes'].includes(key[1])) break
    out.push(body.replace(/\s+$/, ''))
  }
  return out.join('\n').trim()
}

async function build() {
  const parts = [
    'Hyphenation pattern notices',
    '===========================',
    '',
    'Sonata estimates syllables with TeX hyphenation patterns from the hyph-utf8 project',
    '(https://github.com/hyphenation/tex-hyphen), as converted to JavaScript by the `hyphen` package',
    '(ISC, https://github.com/ytiurin/hyphen). Each pattern file stays under its own licence. Below is',
    'the copyright and licence notice from the header of each original file Sonata ships, unchanged,',
    'from tex-hyphen commit ' + COMMIT + '.',
    'Generated by tools/hyph-notices.js; do not edit by hand.',
    ''
  ]
  // loop: SERIAL-REQUIRED — one fetch per shipped pattern file (20), in order, tool only
  for (const [code, lang] of PATTERNS) {
    // error: PASSES-ON — a failed fetch stops the tool (no partial file is written)
    const res = await fetch(RAW(code))
    if (!res.ok) throw new Error(code + ': HTTP ' + res.status)
    const text = notice(await res.text())
    if (!/licen[cs]e:/.test(text)) throw new Error(code + ': no licence block found')
    parts.push('-'.repeat(78), `${lang} (${code}): hyph-${code}.tex`, RAW(code), '-'.repeat(78), '', text, '')
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, parts.join('\n'))
  console.log('wrote ' + path.relative(process.cwd(), OUT) + ' (' + PATTERNS.length + ' pattern files)')
}

function check() {
  const text = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  const missing = PATTERNS.filter(([code]) => !text.includes(`(${code}): hyph-${code}.tex`)).map(([code]) => code)
  if (missing.length) { console.error('hyphenation-NOTICES.txt lacks: ' + missing.join(', ')); process.exit(1) }
  console.log('hyphenation-NOTICES.txt covers all ' + PATTERNS.length + ' shipped pattern files')
}

if (require.main === module) {
  if (process.argv.includes('--check')) check()
  // error: SHOWN — printed, exit 1
  else build().catch((e) => { console.error(e.message); process.exit(1) })
}
module.exports = { notice }
